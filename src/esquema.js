// As tabelas do notebook, no Postgres (Supabase e PGlite). Idempotente: rodar
// de novo não muda nada.
//
// Os nomes são únicos sem diferenciar maiúsculas entre irmãos, como o COLLATE
// NOCASE do SQLite de antes: o índice é sobre lower(nome), e toda comparação de
// nome usa lower() dos dois lados.
//
// concluido_em é texto ISO 8601 em UTC (2026-11-18T21:07:05Z), o mesmo formato
// que o SQLite guardava, então a cópia não converte nada.

export const ESQUEMA = `
  CREATE TABLE IF NOT EXISTS cadernos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario text NOT NULL,
    nome text NOT NULL,
    ordem integer NOT NULL,
    concluido_em text
  );
  CREATE TABLE IF NOT EXISTS disciplinas (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caderno_id integer NOT NULL REFERENCES cadernos(id) ON DELETE CASCADE,
    nome text NOT NULL,
    ordem integer NOT NULL,
    concluido_em text
  );
  CREATE TABLE IF NOT EXISTS sessoes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_id integer NOT NULL REFERENCES disciplinas(id) ON DELETE CASCADE,
    nome text NOT NULL,
    ordem integer NOT NULL,
    concluido_em text
  );
  CREATE TABLE IF NOT EXISTS materiais (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sessao_id integer NOT NULL REFERENCES sessoes(id) ON DELETE CASCADE,
    nome text NOT NULL,
    ordem integer NOT NULL,
    concluido_em text
  );
  CREATE UNIQUE INDEX IF NOT EXISTS cadernos_nome ON cadernos (usuario, lower(nome));
  CREATE UNIQUE INDEX IF NOT EXISTS disciplinas_nome ON disciplinas (caderno_id, lower(nome));
  CREATE UNIQUE INDEX IF NOT EXISTS sessoes_nome ON sessoes (disciplina_id, lower(nome));
  CREATE UNIQUE INDEX IF NOT EXISTS materiais_nome ON materiais (sessao_id, lower(nome));
  -- A próxima posição de um item novo é MAX(ordem) entre os irmãos. Sem estes
  -- índices, importar 20 mil materiais numa sessão varria os irmãos a cada
  -- inserção (86 s no SQLite, 2026-11-12).
  CREATE INDEX IF NOT EXISTS cadernos_ordem ON cadernos (usuario, ordem);
  CREATE INDEX IF NOT EXISTS disciplinas_ordem ON disciplinas (caderno_id, ordem);
  CREATE INDEX IF NOT EXISTS sessoes_ordem ON sessoes (disciplina_id, ordem);
  CREATE INDEX IF NOT EXISTS materiais_ordem ON materiais (sessao_id, ordem);
`;

// Só no Supabase. Tudo que fica no schema public sai pela API de dados dele
// (PostgREST) pra quem tem a chave anon, que é pública. Com RLS ligada e sem
// política nenhuma, anon e authenticated não leem nada; o notebook entra como o
// dono das tabelas, que não passa pela RLS. Os GRANTs saem também, por garantia.
export const TRANCAR_SUPABASE = ["cadernos", "disciplinas", "sessoes", "materiais"]
  .map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY; REVOKE ALL ON ${t} FROM anon, authenticated;`)
  .join("\n");

export const TABELAS = ["cadernos", "disciplinas", "sessoes", "materiais"];
